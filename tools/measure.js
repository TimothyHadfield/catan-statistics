// Measures the computer levels in computer-only games and writes js/strength.js (shown in Settings).
//   node tools/measure.js [games]
const fs = require('fs'), path = require('path');
const { table } = require('./sim.js');
const g = +process.argv[2] || 300;
const pct = (w, n) => Math.round(w / n * 100) + '%';
const rows = [];
const t3 = table(['hard', 'medium', 'easy'], g);
rows.push(['3 players: Hard / Medium / Easy', g, `${pct(t3.wins.hard, g)} / ${pct(t3.wins.medium, g)} / ${pct(t3.wins.easy, g)}`]);
const t3b = table(['hard', 'medium', 'medium'], g);
rows.push(['Hard vs two Medium (fair 33%)', g, 'Hard ' + pct(t3b.wins.hard, g)]);
const t3c = table(['medium', 'easy', 'easy'], g);
rows.push(['Medium vs two Easy (fair 33%)', g, 'Medium ' + pct(t3c.wins.medium, g)]);
const t4 = table(['hard', 'medium', 'medium', 'medium'], g);
rows.push(['Hard vs three Medium (fair 25%)', g, 'Hard ' + pct(t4.wins.hard, g)]);
// 5-6 players: big board with the extra build step
const t5 = table(['hard', 'medium', 'medium', 'medium', 'medium'], g);
rows.push(['5 players: Hard vs four Medium (fair 20%)', g, 'Hard ' + pct(t5.wins.hard, g)]);
const t6 = table(['hard', 'medium', 'medium', 'medium', 'medium', 'medium'], g);
rows.push(['6 players: Hard vs five Medium (fair 17%)', g, 'Hard ' + pct(t6.wins.hard, g)]);
const t6b = table(['medium', 'easy', 'easy', 'easy', 'easy', 'easy'], g);
rows.push(['6 players: Medium vs five Easy (fair 17%)', g, 'Medium ' + pct(t6b.wins.medium, g)]);
const out = { measured: new Date().toISOString().slice(0, 10), games: g, rows, avgTurns: t3.avgTurns };
fs.writeFileSync(path.join(__dirname, '..', 'js', 'strength.js'), '// GENERATED by tools/measure.js (' + out.measured + ')\nwindow.CATAN_STRENGTH = ' + JSON.stringify(rows) + ';\n');
console.log(JSON.stringify(out, null, 1));
